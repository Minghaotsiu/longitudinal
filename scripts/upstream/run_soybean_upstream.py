import os 
import subprocess
import argparse
import glob
import pandas as pd
from datetime import datetime
import sys

PYTHON = os.path.basename(sys.executable)

def run_command(command, description=None, exit_on_error=True):
    if description:
        print(f"{description}...")
    try:
        subprocess.run(command, shell=True, check=True)
        return True
    except subprocess.CalledProcessError as e:
        print(f"执行命令失败: {command}")
        print(e)
        if exit_on_error:
            sys.exit(1)
        return False

def get_new_file(command, description=None):
    """
    黑科技函数：模拟人类的眼睛。
    记录运行命令前后文件夹里多出了哪个新文件，这就是我们需要传给下一步的文件名。
    """
    before_files = set(os.listdir('.'))
    run_command(command, description)
    after_files = set(os.listdir('.'))
    
    new_files = list(after_files - before_files)
    if not new_files:
        raise FileNotFoundError(f"运行 '{command}' 后没有发现生成新文件！")
    
    # 过滤掉运行过程中可能产生的隐藏文件或脚本自身，优先找数据表
    data_files = [f for f in new_files if f.endswith(('.txt', '.csv', '.xlsx', '.tsv'))]
    if data_files:
        # 如果有多个，取最新生成的那个
        return sorted(data_files, key=os.path.getmtime, reverse=True)[0]
    return sorted(new_files, key=os.path.getmtime, reverse=True)[0]

def find_matching_directory(prefix, search_dir='.'):
    matching_dirs = glob.glob(os.path.join(search_dir, prefix + '*'))
    if not matching_dirs:
        raise FileNotFoundError(f"未找到前缀为 '{prefix}' 的目录")
    return max(matching_dirs, key=os.path.getctime)

def create_list_bam(data, star_out_dir, trim_fastqc_dir):
    list_bam_path = os.path.join(trim_fastqc_dir, 'list_bam.txt')
    with open(list_bam_path, 'w') as f:
        for sample_name in data["sample"].unique():
            bam_files = glob.glob(os.path.join(star_out_dir, f'{sample_name}*.sorted.bam'))
            if bam_files:
                f.write(f"{sample_name}\t{bam_files[0]}\n")
            else:
                print(f"警告: 未找到样本 {sample_name} 的 sorted.bam 文件")
    return list_bam_path

def main():
    parser = argparse.ArgumentParser(description='执行转录组分析流程(豆豆源版)')
    parser.add_argument(
        '-m',
        '--sample-manifest',
        default='samples.tsv',
        help='Sample manifest generated by prepare_delivery.py.',
    )
    args = parser.parse_args()

    dangqianmulu = os.getcwd()

    current_folder_name = os.path.basename(os.path.abspath(dangqianmulu))
    out_prefix = current_folder_name

    print(f"[*] 当前运行目录: {dangqianmulu}")
    print(f"[*] 输出文件前缀: {out_prefix}")

    log_file = "pipeline_doudou.log"
    with open(log_file, "a") as log:
        print(f"[{datetime.now()}] 开始执行转录组分析流程(人源版)...", file=log)
        print(f"[{datetime.now()}] 当前运行目录: {dangqianmulu}", file=log)
        print(f"[{datetime.now()}] 输出文件前缀: {out_prefix}", file=log)

    script_dir = os.path.dirname(os.path.abspath(__file__))
    xieyimulu = os.environ.get(
        "SOYBEAN_PROTOCOL_DIR",
        os.path.join(script_dir, "protocol"),
    )
    if not os.path.isdir(xieyimulu):
        raise FileNotFoundError(f"Protocol directory not found: {xieyimulu}")

    # 第零步: 解压文件
    print("第零步: 解压原始测序文件...")
    gz_files = glob.glob("*.fq.gz") + glob.glob("*.fastq.gz")
    if gz_files:
        for gz in gz_files:
            run_command(f"gunzip -c {gz} > {gz[:-3]} && rm -f {gz}", f"解压 {gz}")
    else:
        print("未检测到 .gz 压缩文件，默认已解压，跳过。")

    # 第一步: 复制基础脚本
    print("第一步: 复制基础脚本...")
    for filename in ["S0.raw_fastqc.py", "S1.adapters_RNA.fasta", "S1.trim_fastqc.py"]:
        run_command(f"cp {os.path.join(xieyimulu, filename)} .", f"复制 {filename}")

    # 第二、三步: 质控
    print("第二步: 质量评估...")
    run_command(f"{PYTHON} S0.raw_fastqc.py")

    print("第三步: 质控...")
    run_command(f"{PYTHON} S1.trim_fastqc.py")

    # 第四步: 比对
    print("第四步: 比对...")
    os.makedirs("star_out", exist_ok=True)
    run_command(f"cp {os.path.join(xieyimulu, 'code_S2-10.doudou/S2.star_map_ver0.02.py')} .")

    trim_fastqc_dir = find_matching_directory('trim_fastqc_', search_dir=dangqianmulu)
    os.chdir(trim_fastqc_dir)
    run_command(f"cp {os.path.join(dangqianmulu, 'S2.star_map_ver0.02.py')} .")
    run_command("chmod +x S2.star_map_ver0.02.py")
    run_command(f"{PYTHON} S2.star_map_ver0.02.py")
    os.chdir("..")

    # 第五步: 统计
    star_out_dir = find_matching_directory('star_out_', search_dir=trim_fastqc_dir)
    os.chdir(star_out_dir)
    print("第五步: 比对率计算和基因数统计...")
    
    # 拷贝人源专属的脚本
    scripts_to_copy = [
        "S3.inf_star_map_ver0.1.py",
        "S4.ExonIntron_RNA_v2.2.py", 
        "S5.inf_ExonIntron_v2.py",
        "S10.DepthGeneReadCount_v5.1a.py", 
        "S6.DepthGeneReadCount_v5_doudou.py",
        "sam2bam.py",
        "xlsx_read.py"
    ]

    for filename in scripts_to_copy:
        script_path = os.path.join(xieyimulu, 'code_S2-10.doudou', filename)
        if os.path.exists(script_path):
            run_command(f"cp {script_path} .")
        else:
            print(f"警告: 协议目录中未找到 {filename}")

    run_command(f"{PYTHON} S3.inf_star_map_ver0.1.py -o {out_prefix}")
    run_command(f"{PYTHON} S4.ExonIntron_RNA_v2.2.py")
    run_command(f"{PYTHON} S5.inf_ExonIntron_v2.py -o {out_prefix}")

    manifest_path = (
        args.sample_manifest
        if os.path.isabs(args.sample_manifest)
        else os.path.join(dangqianmulu, args.sample_manifest)
    )
    if not os.path.exists(manifest_path):
        raise FileNotFoundError(f"Sample manifest not found: {manifest_path}")
    data = pd.read_csv(manifest_path, sep="\t")
    if "sample" not in data.columns:
        raise ValueError("The sample manifest must contain a 'sample' column.")
    list_bam_path = create_list_bam(data, star_out_dir, trim_fastqc_dir)

    samples_to_process = data["sample"].unique().tolist()

    for sample_name in samples_to_process:
        bam_files = glob.glob(f"{sample_name}*.sorted.bam")
        if not bam_files:
            print(f"警告: 未找到样本 {sample_name} 的 sorted.bam 文件，跳过该样本")
            continue

        actual_bam = bam_files[0]

        for depth in ['1M', 'raw']:
            if os.path.exists("S10.DepthGeneReadCount_v5.1a.py"):
                ok = run_command(
                    f"{PYTHON} S10.DepthGeneReadCount_v5.1a.py -s {actual_bam} -d {depth} -o {sample_name}",
                    f"运行 S10: {sample_name}, {depth}",
                    exit_on_error=False
                )
                if not ok:
                    print(f"警告: 样本 {sample_name} 在 {depth} 深度下运行失败，已跳过，不影响后续样本。")

    os.remove(list_bam_path)

    # 第六步: 运行 S6 生成 counts
    print("第六步: 运行人源版 S6 脚本生成 individual counts...")
    if os.path.exists("S6.DepthGeneReadCount_v5_doudou.py"):
        run_command(f"{PYTHON} S6.DepthGeneReadCount_v5_doudou.py -d 1M -o 1M", "运行 S6_doudou 脚本")
    else:
        print("致命警告：未检测到 S6_doudou 脚本，后续矩阵无法生成。")
        sys.exit(1)

    # ==============================================================
    # 第七步: 创建 fenxi 目录，分类合并，转换基因名
    # ==============================================================
    print("第七步: 整理目录并合并表达矩阵...")

    fenxi_dir = os.path.join(dangqianmulu, "fenxi")
    fenxi_1m_dir = os.path.join(fenxi_dir, "1M")
    os.makedirs(fenxi_1m_dir, exist_ok=True)
    
    # 将 S6 吐出的 union_counts 分别搬运到指定文件夹
    all_counts = glob.glob("*_union_counts.txt")
    for count_file in all_counts:
        if "_1M_" in count_file:
            run_command(f"cp {count_file} {fenxi_1m_dir}/", f"归档 1M 文件: {count_file}")
        else:
            run_command(f"cp {count_file} {fenxi_dir}/", f"归档 raw 文件: {count_file}")

    # 获取包含 hebing 等脚本的源目录
    protocol_script_dir = os.path.join(xieyimulu, 'code_S2-10.doudou')

    # ---------------- 阶段 7.1：处理 1M ----------------
    os.chdir(fenxi_1m_dir)
    print("\n--- 开始处理 1M 深度数据 ---")
    run_command(f"cp {os.path.join(protocol_script_dir, 'hebing.py')} .")
    run_command(f"cp {os.path.join(protocol_script_dir, 'gene_id2name_v2_doudou.py')} .")
    
    merged_1m_file = get_new_file(f"{PYTHON} hebing.py -o {out_prefix}_1M", "合并 1M 的 counts 矩阵")
    print(f"成功合并！抓取到生成的文件：{merged_1m_file}")
    
    run_command(f"{PYTHON} gene_id2name_v2_doudou.py -i {merged_1m_file} -t f", "为 1M 矩阵转换正常基因名")
    
    # ---------------- 阶段 7.2：处理 Raw (fenxi) ----------------
    os.chdir(fenxi_dir)
    print("\n--- 开始处理 Raw 深度数据及 FPKM 归一化 ---")
    run_command(f"cp {os.path.join(protocol_script_dir, 'hebing.py')} .")
    run_command(f"cp {os.path.join(protocol_script_dir, 'S3.count_fpkm_doudou.py')} .")
    run_command(f"cp {os.path.join(protocol_script_dir, 'gene_id2name_v2_doudou.py')} .")
    
    merged_raw_file = get_new_file(f"{PYTHON} hebing.py -o {out_prefix}_raw", "合并 Raw counts 矩阵")
    print(f"Raw Counts 合并完成：{merged_raw_file}")
    
    # 跑 FPKM 归一化
    fpkm_file = get_new_file(f"{PYTHON} S3.count_fpkm_doudou.py -o {out_prefix}_FPKM", "进行 FPKM 归一化")
    print(f"FPKM 归一化完成：{fpkm_file}")
    
    # 拿 Raw Counts 去转基因名
    run_command(f"{PYTHON} gene_id2name_v2_doudou.py -i {merged_raw_file} -t f", "为 Raw Counts 矩阵转换正常基因名")

    # 拿 FPKM 文件去转基因名
    run_command(f"{PYTHON} gene_id2name_v2_doudou.py -i {fpkm_file} -t f", "为 FPKM 矩阵转换正常基因名")

    # 收尾
    os.chdir(dangqianmulu)
    print("\n太棒了！所有步骤执行完毕，正常表达矩阵已经安静地躺在 fenxi 文件夹里等你了。")

if __name__ == "__main__":
    main()
